// Run against the loopback-only preview with playwright-cli run-code --filename.
async (page) => {
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:8768');
  await page.setViewportSize({ width: 760, height: 680 });
  const nav = page.getByRole('navigation', { name: '设置分类' });
  const choose = name => nav.getByRole('button', { name, exact: true }).click();
  await nav.waitFor();
  await page.locator('#close-behavior').selectOption('tray');
  await choose('外观');
  await page.locator('.settings-theme-option').filter({ hasText: '白天' }).click();
  await page.locator('.client.light').waitFor();
  await page.screenshot({ path: 'output/playwright/settings-preview/appearance-light.png' });
  await choose('常规');
  assert(await page.locator('#close-behavior').inputValue() === 'tray', 'Close preference was lost when changing pages');
  await choose('看板泳道');
  await page.locator('.lane-pref-list[data-lane-drag-ready="true"]').waitFor();
  await page.getByRole('button', { name: '恢复默认' }).click();
  await page.waitForFunction(() => document.querySelector('.lane-pref-row')?.dataset.status === 'waiting');
  assert(await page.locator('.lane-pref-row').count() === 16, 'Incorrect lane count');
  await page.locator('[data-status="confirmed"] .lane-pref-grip').press('Alt+ArrowUp');
  await page.waitForFunction(() => document.querySelector('.lane-pref-row')?.dataset.status === 'confirmed');
  await choose('提醒');
  await page.locator('#notification-project').waitFor();
  if (await page.locator('#notification-enabled').isChecked()) await page.locator('.notification-switch').click();
  await page.waitForFunction(() => !document.querySelector('#notification-enabled').checked);
  await page.locator('#notification-project').click();
  await page.locator('#notification-search').fill('BRG');
  await page.locator('#notification-project-p').click();
  await page.locator('#notification-inherit').waitFor();
  if (!await page.locator('#notification-inherit').isChecked()) await page.locator('#notification-inherit').check();
  await page.waitForFunction(() => document.querySelector('#notification-inherit')?.checked && !document.querySelector('#notification-enabled')?.checked);
  assert(!await page.locator('#notification-enabled').isChecked(), 'Disabled default was not inherited');
  await page.locator('#notification-inherit').uncheck();
  await page.locator('.notification-switch').click();
  await page.waitForFunction(() => document.querySelector('#notification-enabled').checked);
  await page.screenshot({ path: 'output/playwright/settings-preview/notifications-light.png' });
  await page.locator('#notification-status-open').click();
  await page.getByRole('heading', { name: '目标状态' }).waitFor();
  await page.locator('#notification-all-statuses').uncheck();
  await page.waitForFunction(() => !document.querySelector('#notification-status-processing')?.checked);
  await page.locator('#notification-status-processing').check();
  await page.locator('#notification-back').click();
  await page.waitForFunction(() => document.querySelector('#notification-status-open')?.textContent.includes('1 个目标状态'));
  await choose('看板泳道');
  await page.locator('.lane-pref-list[data-lane-drag-ready="true"]').waitFor();
  assert(await page.locator('.lane-pref-row').first().getAttribute('data-status') === 'confirmed', 'Lane order was not persisted');
  await choose('提醒');
  await page.locator('#notification-project').click();
  await page.locator('#notification-project-p').click();
  await page.waitForFunction(() => document.querySelector('#notification-inherit') && !document.querySelector('#notification-inherit').checked && document.querySelector('#notification-enabled')?.checked);
  await choose('应用更新');
  assert((await page.locator('.settings-update-app').innerText()).includes('1.0.12'), 'Version was not shown');
  await choose('常规');
  await page.locator('#language-preference').selectOption('en');
  await page.getByRole('navigation', { name: 'Settings categories' }).waitFor();
  assert(await page.getByRole('button', { name: 'App updates' }).count() === 1, 'English navigation missing');
  await page.getByRole('button', { name: 'Appearance' }).click();
  await page.locator('.settings-theme-option').filter({ hasText: 'Dark' }).click();
  await page.locator('.client.dark').waitFor();
  await page.setViewportSize({ width: 620, height: 520 });
  const fit = await page.evaluate(() => ({ width: document.documentElement.scrollWidth, viewport: innerWidth, footer: document.querySelector('.settings-footer').getBoundingClientRect().bottom, height: innerHeight }));
  assert(fit.width <= fit.viewport && fit.footer <= fit.height + 1, 'Minimum window overflows');
  await page.screenshot({ path: 'output/playwright/settings-preview/appearance-dark-minimum.png' });
  assert(errors.length === 0, 'Browser errors: ' + errors.join('; '));
  return 'Settings navigation, preferences, project inheritance, lane persistence and bilingual layouts passed.';
}
