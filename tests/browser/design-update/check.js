// Run with playwright-cli run-code against the loopback preview.
async (page) => {
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const order = () => page.locator('.lane-pref-list > [data-status]').evaluateAll(rows => rows.map(row => row.dataset.status));
  const first = () => page.locator('.lane-pref-list > [data-status]').first().getAttribute('data-status');
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.locator('.lane-pref-list[data-lane-drag-ready="true"]').waitFor();
  await page.getByRole('button', { name: '恢复默认' }).click();
  await page.waitForFunction(() => document.querySelector('.lane-pref-row')?.dataset.status === 'waiting');
  const before = await order();
  const source = page.locator('[data-status="reproducing"] .lane-pref-grip');
  const target = page.locator('[data-status="confirmed"]');
  await source.scrollIntoViewIfNeeded();
  const a = await source.boundingBox(), b = await target.boundingBox();
  await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2);
  await page.mouse.down();
  await page.mouse.move(b.x + b.width / 2, b.y + b.height * .2, { steps: 10 });
  assert(await target.evaluate(row => row.classList.contains('drop-before')), 'No insertion marker');
  assert(await page.locator('.lane-pref-ghost').count() === 1, 'No drag preview');
  await page.mouse.up();
  await page.waitForFunction(() => [...document.querySelectorAll('.lane-pref-list > [data-status]')].map(x => x.dataset.status).slice(0, 3).join(',') === 'waiting,reproducing,confirmed');
  await page.reload();
  await page.locator('.lane-pref-list[data-lane-drag-ready="true"]').waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll('.lane-pref-list > [data-status]')].map(x => x.dataset.status).slice(0, 3).join(',') === 'waiting,reproducing,confirmed');
  await page.locator('[data-status="reproducing"] .lane-pref-grip').press('Alt+ArrowDown');
  await page.waitForFunction(() => [...document.querySelectorAll('.lane-pref-list > [data-status]')].map(x => x.dataset.status).slice(0, 3).join(',') === 'waiting,confirmed,reproducing');
  // Holding a real pointer at the visible bottom scrolls; Escape cancels the move.
  const grip = page.locator('[data-status="reproducing"] .lane-pref-grip');
  const g = await grip.boundingBox(), list = await page.locator('.lane-pref-list').boundingBox();
  await page.mouse.move(g.x + g.width / 2, g.y + g.height / 2); await page.mouse.down();
  await page.mouse.move(list.x + list.width / 2, Math.min(list.y + list.height - 5, 895), { steps: 10 });
  await page.waitForFunction(() => document.querySelector('.lane-pref-list').scrollTop > 20);
  await page.keyboard.press('Escape'); await page.mouse.up();
  assert((await order()).slice(0, 3).join(',') === 'waiting,confirmed,reproducing', 'Escape changed order');
  await page.locator('.lane-pref-list').evaluate(element => element.scrollTop = 0);
  const projects = page.getByRole('combobox', { name: '配置项目' });
  const options = await projects.locator('option').evaluateAll(items => items.map(item => ({ value: item.value, label: item.textContent })));
  const projectA = options.find(item => item.label === '示例项目 A').value;
  const projectB = options.find(item => item.label === '示例项目 B').value;
  await projects.selectOption(projectB);
  await page.waitForFunction(() => document.querySelector('.lane-pref-row')?.dataset.status === 'closed');
  await projects.selectOption(projectA);
  await page.waitForFunction(() => document.querySelector('.lane-pref-row')?.dataset.status === 'waiting');
  await page.getByRole('button', { name: '复制其他项目的配置' }).click();
  assert(await page.locator('.lane-pref-copy-preview li').first().textContent() === '已关闭', 'Source preview is wrong');
  await page.getByRole('button', { name: '取消', exact: true }).click();
  assert(await first() === 'waiting', 'Cancel changed target order');
  await page.getByRole('button', { name: '复制其他项目的配置' }).click();
  await page.getByRole('button', { name: '复制并保存' }).click();
  await page.waitForFunction(() => document.querySelector('.lane-pref-row')?.dataset.status === 'closed');
  await page.reload();
  await page.locator('.lane-pref-list[data-lane-drag-ready="true"]').waitFor();
  await page.waitForFunction(() => document.querySelector('.lane-pref-row')?.dataset.status === 'closed');
  if (!await page.locator('.client.dark').count()) { await page.getByRole('button', { name: '切换日夜模式' }).click(); await page.locator('.client.dark').waitFor(); }
  await page.screenshot({ path: 'output/playwright/design-update/lanes-dark.png', fullPage: true });
  await page.getByRole('button', { name: '切换日夜模式' }).click();
  await page.locator('.client.light').waitFor();
  await page.screenshot({ path: 'output/playwright/design-update/lanes-light.png', fullPage: true });
  await page.getByRole('button', { name: '处理记录', exact: true }).click();
  const cards = page.locator('.bug-record');
  await cards.first().waitFor();
  assert(await cards.count() === 2, 'Expected reply and structured record');
  assert((await cards.first().innerText()).includes('普通回复'), 'Newest reply is not first');
  assert((await cards.nth(1).innerText()).includes('调整菜单入口'), 'Structured field not displayed');
  await cards.nth(1).getByRole('button', { name: '收起' }).click();
  assert(await cards.nth(1).getByRole('button', { name: '展开' }).getAttribute('aria-expanded') === 'false', 'Record did not collapse');
  assert((await cards.nth(1).innerText()).includes('修复完成'), 'Collapsed summary is missing');
  assert(await cards.first().getByRole('button', { name: '收起' }).count() === 1, 'Collapsing one changed another');
  await cards.nth(1).getByRole('button', { name: '展开' }).click();
  await cards.nth(1).getByRole('button', { name: '收起' }).waitFor();
  await page.screenshot({ path: 'output/playwright/design-update/records-light.png', fullPage: true });
  await page.getByRole('button', { name: '切换日夜模式' }).click();
  await page.locator('.client.dark').waitFor();
  await page.screenshot({ path: 'output/playwright/design-update/records-dark.png', fullPage: true });
  assert(before.length > 0 && new Set(before).size === before.length, 'Lane order contains duplicates');
  return 'PASS: drag, insertion marker, edge scrolling, Escape, keyboard, persistence, per-project copy/cancel, independent collapse, chronological order, light and dark';
}
